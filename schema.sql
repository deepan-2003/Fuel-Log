-- Run this in Supabase Dashboard > SQL Editor.
-- The Python app also creates these tables automatically on startup.
CREATE TABLE IF NOT EXISTS public.vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_no TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL DEFAULT '',
    driver TEXT NOT NULL DEFAULT '',
    tank_capacity DOUBLE PRECISION NOT NULL DEFAULT 0,
    fc_date DATE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.fuel_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES public.vehicles(id) ON DELETE CASCADE,
    entry_date DATE NOT NULL,
    closing_km DOUBLE PRECISION NOT NULL,
    starting_km DOUBLE PRECISION NOT NULL,
    fuel_litres DOUBLE PRECISION NOT NULL,
    bill_no TEXT NOT NULL DEFAULT '',
    bill_date DATE,
    amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    remarks TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_entries_vehicle_date
    ON public.fuel_entries(vehicle_id, entry_date);
CREATE INDEX IF NOT EXISTS ix_entries_date
    ON public.fuel_entries(entry_date);

CREATE TABLE IF NOT EXISTS public.settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL DEFAULT ''
);
